data class WebRpcError(
    val error: String,
    val code: Int,
    override val message: String,
    val causeString: String,
    val status: Int,
    val errorKind: ErrorKind = ErrorKind.fromCode(code),
) : Exception(message)

@Serializable
private data class WebRpcErrorPayload(
    @SerialName("error") val error: String? = null,
    @SerialName("code") val code: Int? = null,
    @SerialName("msg") val message: String? = null,
    @SerialName("cause") val causeString: String? = null,
    @SerialName("status") val status: Int? = null,
)

fun decodeWebRpcError(
    statusCode: Int,
    body: String,
    json: Json = WebRpcJson,
): WebRpcError {
    return try {
        val payload = json.decodeFromString<WebRpcErrorPayload>(body)
        val code = payload.code ?: ErrorKind.UNKNOWN.code
        WebRpcError(
            error = payload.error ?: "WebrpcEndpoint",
            code = code,
            message = payload.message ?: "endpoint error",
            causeString = payload.causeString.orEmpty(),
            status = payload.status ?: statusCode,
            errorKind = ErrorKind.fromCode(code),
        )
    } catch (_: Throwable) {
        WebRpcError(
            error = "WebrpcBadResponse",
            code = ErrorKind.UNKNOWN.code,
            message = "Unable to decode error response",
