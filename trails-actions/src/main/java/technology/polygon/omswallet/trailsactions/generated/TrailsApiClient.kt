// region Runtime
val WebRpcJson: Json = Json {
    ignoreUnknownKeys = true
}

data class WebRpcHttpResponse(
    val statusCode: Int,
    val body: String,
    val headers: Map<String, String> = emptyMap(),
)

interface WebRpcTransport {
    suspend fun post(
        baseUrl: String,
        path: String,
        body: String,
        headers: Map<String, String> = emptyMap(),
    ): WebRpcHttpResponse
}

class WebRpcTransportException(
    message: String,
    cause: Throwable? = null,
) : IOException(message, cause)
class OkHttpWebRpcTransport(
    private val okHttpClient: OkHttpClient = OkHttpClient(),
) : WebRpcTransport {
    override suspend fun post(
        baseUrl: String,
        path: String,
        body: String,
        headers: Map<String, String>,
    ): WebRpcHttpResponse = withContext(Dispatchers.IO) {
        val request = Request.Builder()
            .url(joinUrl(baseUrl, path))
            .post(body.toRequestBody(jsonMediaType))
            .apply {
                headers.forEach { (name, value) -> addHeader(name, value) }
            }
            .build()

        try {
            okHttpClient.newCall(request).execute().use { response ->
                val responseBody = response.body?.string().orEmpty()
                val responseHeaders = response.headers.toMultimap()
                    .mapValues { (_, values) -> values.lastOrNull().orEmpty() }
                WebRpcHttpResponse(
                    statusCode = response.code,
                    body = responseBody,
                    headers = responseHeaders,
                )
            }
        } catch (exception: IOException) {
            throw WebRpcTransportException("WebRPC HTTP request failed", exception)
        }
    }

    companion object {
        private val jsonMediaType = "application/json; charset=utf-8".toMediaType()
    }
}

private fun joinUrl(baseUrl: String, path: String): String =
    baseUrl.trimEnd('/') + "/" + path.trimStart('/')

suspend inline fun <O> executeWebRpc(
    baseUrl: String,
    urlPath: String,
    body: String,
    transport: WebRpcTransport,
    headers: Map<String, String> = emptyMap(),
    json: Json = WebRpcJson,
    crossinline decodeSuccess: (body: String, json: Json) -> O,
): O {
    val response = try {
        transport.post(
            baseUrl = baseUrl,
            path = urlPath,
            body = body,
            headers = headers,
        )
    } catch (e: CancellationException) {
        throw e
    } catch (e: WebRpcTransportException) {
        throw e
    } catch (e: Throwable) {
        throw WebRpcTransportException("WebRPC request failed", e)
    }

    if (response.statusCode !in 200..299) {
        throw decodeWebRpcError(response.statusCode, response.body, json)
    }

    return decodeSuccess(response.body, json)
}
