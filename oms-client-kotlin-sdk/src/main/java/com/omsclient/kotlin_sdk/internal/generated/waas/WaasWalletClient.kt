suspend inline fun <O> executeWebRpc(
    baseUrl: String,
    urlPath: String,
    body: String,
    transport: WebRpcTransport,
    headers: Map<String, String> = emptyMap(),
    json: Json = WebRpcJson,
    crossinline decodeSuccess: (body: String, json: Json) -> O,
): O {
    val response = try {
        transport.post(
            baseUrl = baseUrl,
            path = urlPath,
            body = body,
            headers = headers,
        )
    } catch (e: CancellationException) {
        throw e
    } catch (e: WebRpcTransportException) {
        throw e
    } catch (e: Throwable) {
        throw WebRpcTransportException("WebRPC request failed", e)
    }

    if (response.statusCode !in 200..299) {
        throw decodeWebRpcError(response.statusCode, response.body, json)
    }

    return decodeSuccess(response.body, json)
